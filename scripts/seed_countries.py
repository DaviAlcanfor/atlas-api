"""One-off generator: data_out/wikidata.json (+ seed_legacy/*.json) -> content/polities/<id>.yaml.

SEED POLICY (option A, chosen 2026-11-11 and documented in README):
- Every modern country needs a polity row (country_facts.iso2 -> polities.iso2, start_year NOT NULL).
- start_year is a PLACEHOLDER (PLACEHOLDER_START) with start_precision "century", which in this
  project means "formation date NOT curated yet". Curate a country by editing its YAML.
- The placeholder is after 1945 on purpose, so modern countries do not show up in /polities?year=
  for earlier years; the cost is that countries formed after 1946 appear a bit early.
- type is "other" (not curated). ids: pt-BR name without accents, except the contract's 8 seed ids.
- The 5 legacy files (AI-written, UNVERIFIED) become events with `# TODO verify`, no sources.
Run: python scripts/seed_countries.py   (overwrites generated files; skips none)
"""

import json
import re
import unicodedata
from pathlib import Path

PLACEHOLDER_START = 1946
CONTRACT_IDS = {"AT": "austria", "BR": "brazil", "DE": "germany", "EG": "egypt",
                "JP": "japan", "TR": "turkey", "RU": "russia", "RS": "serbia"}
OUT = Path("content/polities")


def slug(name: str) -> str:
    plain = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", plain.lower()).strip("-")


def q(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)  # JSON strings are valid YAML scalars


def legacy_events(iso2: str, legacy: dict) -> list[str]:
    lines = ["events:"]
    for i, h in enumerate(legacy["historia"], 1):
        year = h["ano"]
        precision = "circa" if year < 1000 else "exact"
        lines += [
            f"  - id: {iso2.lower()}-legacy-{i}  # TODO verify (AI-written from memory, unverified)",
            f"    year_start: {year}",
            f"    precision: {precision}",
            f"    title: {q(h['evento'])}",
            '    summary: ""',
            "    kind: other",
            "    source_ids: []",
        ]
    return lines


def main() -> None:
    countries = json.loads(Path("data_out/wikidata.json").read_text(encoding="utf-8"))["countries"]
    OUT.mkdir(parents=True, exist_ok=True)
    ids: dict[str, str] = {}
    for iso2, c in sorted(countries.items()):
        pid = CONTRACT_IDS.get(iso2) or slug(c["name"])
        assert pid not in ids, f"slug collision: {pid} ({iso2} vs {ids[pid]})"
        ids[pid] = iso2
        legacy_file = Path(f"seed_legacy/{iso2}.json")
        legacy = json.loads(legacy_file.read_text(encoding="utf-8")) if legacy_file.exists() else None
        lines = [
            f"# GENERATED by scripts/seed_countries.py. start_year {PLACEHOLDER_START} is a PLACEHOLDER (see script).",
            f"id: {pid}",
            f"name: {q(c['name'])}",
            "type: other",
            f"start_year: {PLACEHOLDER_START}  # TODO curate formation date",
            "start_precision: century  # = placeholder, not curated",
            f'iso2: "{iso2}"',  # quoted: bare NO (Norway) is a YAML boolean
            f"wikidata_qid: {c['qid']}",
        ]
        if legacy:
            lines += [
                f"regime: {q(legacy['regime'])}  # TODO verify (legacy, AI-written)",
                f"summary: {q(legacy['resumo'])}  # TODO verify (legacy, AI-written)",
                "politics:",
                f"  system: {q(legacy['politica_atual']['sistema'])}  # TODO verify",
                f"  note: {q(legacy['politica_atual']['nota'])}",
                f"  updated_at: {legacy['atualizado_em']}",
            ] + legacy_events(iso2, legacy)
        (OUT / f"{pid}.yaml").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(ids)} polity files to {OUT}")


if __name__ == "__main__":
    main()
